//! Pièces justificatives d'une demande de structure (CLAUDE.md §14,
//! « Pièces justificatives » ; reste de l'étape 3.7, ouvert avec le type
//! `pharmacie`, décision D4 du 2026-11-16). Tables de la migration 0012 :
//! `piece_justificative` (description) et `piece_contenu` (le fichier, à
//! part : seule la route de téléchargement de l'équipe le lit).
//!
//! Règles de §14, sources OWASP *File Upload Cheat Sheet* :
//! - formats PDF, JPEG et PNG seulement, **5 Mio** au plus ;
//! - type déterminé par les **premiers octets** du fichier (« validate the
//!   file type, don't trust the Content-Type header as it can be spoofed »),
//!   jamais par l'extension, le `Content-Type` ou le nom envoyés ;
//! - le nom envoyé n'est jamais gardé (« change the filename to something
//!   generated by the application ») : la pièce est désignée par son
//!   identifiant ;
//! - empreinte SHA-256 enregistrée ;
//! - une pièce ne se modifie jamais : pendant le brouillon, un nouveau dépôt
//!   du même type ajoute une ligne et passe l'ancienne à `active = false` ;
//!   rien n'est effacé.
//!
//! Ordre des verrous : la structure seule (comme les autres opérations du
//! créateur sur sa demande, §12).

use chrono::{DateTime, NaiveDate, Utc};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use sqlx::PgPool;
use sqlx::types::Uuid;

use crate::structure::TypeStructure;

/// 5 Mio au plus (§14) ; même borne que les CHECK de la migration 0012.
pub const TAILLE_MAX_OCTETS: usize = 5 * 1024 * 1024;

// La colonne `contenu` (table `piece_contenu`) n'est jamais sélectionnée
// ici (§14). Macro : sqlx 0.9 n'accepte que des chaînes SQL littérales.
macro_rules! select_piece {
    () => {
        "SELECT p.id, p.type_piece, p.numero, p.date_piece, p.type_mime, p.taille, \
                encode(p.sha256, 'hex') AS sha256, p.active, p.date_depot \
         FROM piece_justificative p"
    };
}

// Garde-fou technique sur le numéro saisi (même principe que le motif de
// 1 000 caractères) ; la base exige seulement un numéro non vide.
const NUMERO_MAX: usize = 100;

/// Liste fermée de la migration 0012.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum TypePiece {
    AutorisationCreation,
    AutorisationOuvertureExploitation,
}

impl TypePiece {
    pub fn as_str(self) -> &'static str {
        match self {
            TypePiece::AutorisationCreation => "autorisation_creation",
            TypePiece::AutorisationOuvertureExploitation => "autorisation_ouverture_exploitation",
        }
    }
}

/// Type d'un fichier d'après ses premiers octets (« magic numbers ») :
/// - PDF : l'en-tête `%PDF-` (ISO 32000-1, §7.5.2 « File Header ») ;
/// - PNG : la signature de 8 octets `89 50 4E 47 0D 0A 1A 0A` (PNG,
///   W3C/ISO 15948, §5.2 « PNG signature ») ;
/// - JPEG : le marqueur SOI `FF D8` suivi d'un marqueur `FF` (ITU-T T.81,
///   annexe B, B.1.1.3 et tableau B.1).
///
/// `None` pour tout le reste (SVG, HEIC, exécutables…), refusé.
pub fn detecter_type(octets: &[u8]) -> Option<&'static str> {
    if octets.starts_with(b"%PDF-") {
        Some("application/pdf")
    } else if octets.starts_with(&[0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A]) {
        Some("image/png")
    } else if octets.starts_with(&[0xFF, 0xD8, 0xFF]) {
        Some("image/jpeg")
    } else {
        None
    }
}

#[derive(Debug, thiserror::Error)]
pub enum ErreurPiece {
    /// Inexistante, ou créée par une autre personne : jamais distinguées.
    #[error("Structure inconnue.")]
    StructureInconnue,
    #[error("Les pièces ne se déposent que sur une demande en brouillon.")]
    TransitionInvalide { statut_actuel: String },
    #[error("Cette pièce n'est pas demandée pour ce type de structure.")]
    PieceNonPrevue,
    #[error("Le fichier doit être un PDF, un JPEG ou un PNG.")]
    FormatRefuse,
    #[error("Le fichier est vide.")]
    FichierVide,
    #[error("Le fichier dépasse 5 Mo.")]
    FichierTropGrand,
    /// Le message ne cite que le nom du champ, jamais la valeur saisie.
    #[error("{0}")]
    DonneesInvalides(String),
    #[error("erreur interne : {0}")]
    Interne(String),
}

impl From<sqlx::Error> for ErreurPiece {
    fn from(erreur: sqlx::Error) -> Self {
        ErreurPiece::Interne(erreur.to_string())
    }
}

/// Une pièce, sans son contenu.
#[derive(Debug, Serialize, sqlx::FromRow)]
pub struct Piece {
    pub id: Uuid,
    pub type_piece: String,
    pub numero: String,
    pub date_piece: NaiveDate,
    pub type_mime: String,
    pub taille: i32,
    /// Empreinte SHA-256 en hexadécimal.
    pub sha256: String,
    pub active: bool,
    pub date_depot: DateTime<Utc>,
}

/// Pièce vue par l'équipe : avec les autres demandes qui portent le même
/// numéro normalisé pour le même type de pièce (avertissement de §14).
#[derive(Debug, Serialize)]
pub struct PieceAdministrateur {
    #[serde(flatten)]
    pub piece: Piece,
    pub meme_numero_dans: Vec<Uuid>,
}

/// `POST /api/structures/{id}/pieces/{type_piece}` : dépôt par le créateur
/// (son compte patient), sur une demande en brouillon. Renvoie la pièce
/// enregistrée.
pub async fn deposer(
    pool: &PgPool,
    patient_compte_id: Uuid,
    structure_id: Uuid,
    type_piece: TypePiece,
    numero: &str,
    date_piece: NaiveDate,
    contenu: &[u8],
) -> Result<Piece, ErreurPiece> {
    // Contrôles sans base d'abord.
    if contenu.is_empty() {
        return Err(ErreurPiece::FichierVide);
    }
    if contenu.len() > TAILLE_MAX_OCTETS {
        return Err(ErreurPiece::FichierTropGrand);
    }
    let type_mime = detecter_type(contenu).ok_or(ErreurPiece::FormatRefuse)?;
    let numero = numero.trim();
    if numero.is_empty() || numero.chars().count() > NUMERO_MAX || numero.chars().any(char::is_control) {
        return Err(ErreurPiece::DonneesInvalides(format!(
            "numero : obligatoire, {NUMERO_MAX} caractères au plus, sans caractère de contrôle."
        )));
    }
    let sha256 = Sha256::digest(contenu).to_vec();

    let mut tx = pool.begin().await?;
    // Même lecture que la soumission : la structure, si et seulement si ce
    // compte patient est celui de son créateur ; verrouillée.
    let ligne: Option<(String, String, bool)> = sqlx::query_as(
        "SELECT s.statut, s.type_structure, $3 > (now() AT TIME ZONE 'Africa/Ouagadougou')::date \
         FROM structure s \
         JOIN compte pro ON pro.id = s.createur_compte_id \
         JOIN compte pat ON pat.utilisateur_id = pro.utilisateur_id AND pat.type_compte = 'patient' \
         WHERE s.id = $1 AND pat.id = $2 \
         FOR UPDATE OF s",
    )
    .bind(structure_id)
    .bind(patient_compte_id)
    .bind(date_piece)
    .fetch_optional(&mut *tx)
    .await?;
    let (statut, type_structure, date_future) = ligne.ok_or(ErreurPiece::StructureInconnue)?;
    if statut != "brouillon" {
        return Err(ErreurPiece::TransitionInvalide { statut_actuel: statut });
    }
    let prevue = TypeStructure::depuis_base(&type_structure)
        .is_some_and(|t| t.pieces_exigees().contains(&type_piece));
    if !prevue {
        return Err(ErreurPiece::PieceNonPrevue);
    }
    // Une autorisation n'est jamais datée de demain (date du Burkina, D9).
    if date_future {
        return Err(ErreurPiece::DonneesInvalides("date_piece : ne peut pas être postérieure à aujourd'hui.".into()));
    }

    // Remplacement pendant le brouillon : l'ancienne pièce reste, inactive.
    sqlx::query("UPDATE piece_justificative SET active = false WHERE structure_id = $1 AND type_piece = $2 AND active")
        .bind(structure_id)
        .bind(type_piece.as_str())
        .execute(&mut *tx)
        .await?;
    let id: Uuid = sqlx::query_scalar(
        "INSERT INTO piece_justificative (structure_id, type_piece, numero, date_piece, type_mime, taille, sha256) \
         VALUES ($1, $2, $3, $4, $5, $6, $7) RETURNING id",
    )
    .bind(structure_id)
    .bind(type_piece.as_str())
    .bind(numero)
    .bind(date_piece)
    .bind(type_mime)
    .bind(contenu.len() as i32)
    .bind(&sha256)
    .fetch_one(&mut *tx)
    .await
    .map_err(|e| match e.as_database_error().and_then(|d| d.constraint()) {
        // Un numéro réduit au seul préfixe « N° » (N2, migration 0012).
        Some("piece_justificative_numero_normalise_non_vide") => {
            ErreurPiece::DonneesInvalides("numero : ne peut pas se réduire à « N° ».".into())
        }
        _ => e.into(),
    })?;
    sqlx::query("INSERT INTO piece_contenu (piece_id, contenu) VALUES ($1, $2)")
        .bind(id)
        .bind(contenu)
        .execute(&mut *tx)
        .await?;
    tx.commit().await?;

    Ok(sqlx::query_as(concat!(select_piece!(), " WHERE p.id = $1")).bind(id).fetch_one(pool).await?)
}

/// Pièces d'une demande, pour son créateur (actives seulement) ; `None` si
/// la structure n'existe pas ou n'est pas la sienne.
pub async fn lister_pour_createur(
    pool: &PgPool,
    patient_compte_id: Uuid,
    structure_id: Uuid,
) -> Result<Option<Vec<Piece>>, sqlx::Error> {
    let a_lui: bool = sqlx::query_scalar(
        "SELECT EXISTS (SELECT 1 FROM structure s \
                        JOIN compte pro ON pro.id = s.createur_compte_id \
                        JOIN compte pat ON pat.utilisateur_id = pro.utilisateur_id AND pat.type_compte = 'patient' \
                        WHERE s.id = $1 AND pat.id = $2)",
    )
    .bind(structure_id)
    .bind(patient_compte_id)
    .fetch_one(pool)
    .await?;
    if !a_lui {
        return Ok(None);
    }
    let pieces = sqlx::query_as(concat!(
        select_piece!(),
        " WHERE p.structure_id = $1 AND p.active ORDER BY p.type_piece"
    ))
    .bind(structure_id)
    .fetch_all(pool)
    .await?;
    Ok(Some(pieces))
}

/// Toutes les pièces d'une structure (anciennes comprises), pour l'équipe,
/// avec l'avertissement des numéros en double.
pub async fn lister_pour_administrateur(pool: &PgPool, structure_id: Uuid) -> Result<Vec<PieceAdministrateur>, sqlx::Error> {
    let pieces: Vec<Piece> = sqlx::query_as(concat!(
        select_piece!(),
        " WHERE p.structure_id = $1 ORDER BY p.type_piece, p.date_depot DESC, p.id DESC"
    ))
    .bind(structure_id)
    .fetch_all(pool)
    .await?;
    let mut resultat = Vec::with_capacity(pieces.len());
    for piece in pieces {
        let meme_numero_dans: Vec<Uuid> = sqlx::query_scalar(
            "SELECT DISTINCT autre.structure_id FROM piece_justificative autre \
             JOIN piece_justificative p ON p.id = $1 \
             WHERE autre.type_piece = p.type_piece AND autre.numero_normalise = p.numero_normalise \
               AND autre.structure_id <> p.structure_id AND autre.active \
             ORDER BY autre.structure_id",
        )
        .bind(piece.id)
        .fetch_all(pool)
        .await?;
        resultat.push(PieceAdministrateur { piece, meme_numero_dans });
    }
    Ok(resultat)
}

/// Contenu d'une pièce, pour la seule route de téléchargement de l'équipe :
/// (type MIME détecté au dépôt, octets). `None` si elle n'existe pas.
pub async fn contenu(pool: &PgPool, piece_id: Uuid) -> Result<Option<(String, Vec<u8>)>, sqlx::Error> {
    sqlx::query_as(
        "SELECT p.type_mime, c.contenu FROM piece_justificative p JOIN piece_contenu c ON c.piece_id = p.id WHERE p.id = $1",
    )
    .bind(piece_id)
    .fetch_optional(pool)
    .await
}

